import React, { useState } from 'react';
import { motion } from 'framer-motion';
import {
  Copy,
  Check,
  HelpCircle,
  Info,
  CornerDownRight,
  ArrowRight,
} from 'lucide-react';
import { useGetAnalysisInterviewQuestions } from '../../api/analysisApi';
import type { InterviewQuestionItem } from '../../types/analysis';

interface InterviewQuestionPreviewProps {
  analysisId: string;
  fallbackItems?: InterviewQuestionItem[];
  onSelectAssumption?: (assumptionId: string) => void;
}

export const InterviewQuestionPreview: React.FC<InterviewQuestionPreviewProps> = ({
  analysisId,
  fallbackItems,
  onSelectAssumption,
}) => {
  const [copiedId, setCopiedId] = useState<string | null>(null);
  const [copiedAll, setCopiedAll] = useState(false);

  const { data, isLoading } = useGetAnalysisInterviewQuestions(analysisId, {
    query: {
      enabled: Boolean(analysisId),
    },
  });

  const responseData = data?.data;
  const isAvailable = responseData?.available ?? true;
  const questions: InterviewQuestionItem[] = responseData?.items || fallbackItems || [];

  const handleCopyOne = async (id: string, text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopiedId(id);
      setTimeout(() => setCopiedId(null), 2000);
    } catch {
      // ignore
    }
  };

  const handleCopyAll = async () => {
    if (questions.length === 0) return;
    const formatted = questions
      .map((q, idx) => {
        return `### Question ${idx + 1}\n**"${q.question}"**\n- Purpose: ${q.purpose}\n- Evidence to Look For: ${q.evidenceToLookFor}${
          q.followUpQuestion ? `\n- Follow-Up: "${q.followUpQuestion}"` : ''
        }\n- Related Assumption ID: ${q.relatedAssumptionId}\n`;
      })
      .join('\n');

    try {
      await navigator.clipboard.writeText(
        `# Mom Test Customer Discovery Script\n\nGenerated by Blindspot AI Phase 02 Engine\n\n${formatted}`
      );
      setCopiedAll(true);
      setTimeout(() => setCopiedAll(false), 2500);
    } catch {
      // ignore
    }
  };

  if (isLoading && questions.length === 0) {
    return (
      <div className="p-8 sm:p-12 rounded-3xl bg-sand-light border border-forest/15 text-center text-forest space-y-3">
        <div className="w-8 h-8 rounded-full border-2 border-purple border-t-transparent animate-spin mx-auto" />
        <p className="text-xs font-mono text-forest/70">Loading non-leading Mom Test questions...</p>
      </div>
    );
  }

  if (!isAvailable) {
    return (
      <div className="p-8 rounded-3xl bg-sand-light border border-dashed border-forest/20 text-center space-y-3">
        <Info className="w-8 h-8 text-forest/40 mx-auto" />
        <h3 className="text-base font-serif font-bold text-forest">Interview Questions Not Available</h3>
        <p className="text-xs text-forest/70 max-w-md mx-auto font-sans leading-relaxed">
          {responseData?.reason || 'This historical analysis predates the Phase 02 engine.'}
        </p>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* Header with Mom Test principles & Copy All button */}
      <div className="p-5 rounded-3xl bg-sand-light border border-forest/15 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div>
          <span className="text-[10px] font-mono font-bold uppercase tracking-widest text-purple bg-purple/10 px-2.5 py-0.5 rounded-full">
            The Mom Test Protocol
          </span>
          <h3 className="text-lg font-serif font-bold text-forest mt-1">
            Grounded Customer Discovery Interview Guide
          </h3>
          <p className="text-xs text-forest/75 font-sans mt-0.5 max-w-xl">
            {questions.length} non-leading questions investigating past behaviors, active workarounds, and actual spending—avoiding hypothetical opinions or premature pitch endorsements.
          </p>
        </div>

        <button
          type="button"
          onClick={handleCopyAll}
          disabled={questions.length === 0}
          className="px-4 py-2 rounded-full text-xs font-bold bg-forest text-sand hover:bg-forest-light transition-all flex items-center gap-1.5 shadow-sm cursor-pointer shrink-0"
        >
          {copiedAll ? (
            <>
              <Check className="w-3.5 h-3.5 text-emerald-400" /> Copied Full Script!
            </>
          ) : (
            <>
              <Copy className="w-3.5 h-3.5 text-purple" /> Copy All Questions
            </>
          )}
        </button>
      </div>

      {/* Questions List */}
      {questions.length === 0 ? (
        <div className="p-10 rounded-3xl bg-sand-light border border-forest/15 text-center text-forest/60 space-y-2">
          <HelpCircle className="w-8 h-8 mx-auto opacity-40 text-purple" />
          <p className="text-sm font-semibold">No interview questions found for this analysis.</p>
        </div>
      ) : (
        <div className="space-y-4">
          {questions.map((q, idx) => {
            const isCopied = copiedId === q.id;

            return (
              <motion.div
                key={q.id || idx}
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                className="p-5 sm:p-6 rounded-3xl bg-sand-light border border-forest/15 hover:border-purple/35 transition-all shadow-sm space-y-4"
              >
                {/* Top Question Row */}
                <div className="flex items-start justify-between gap-3">
                  <div className="flex items-start gap-3">
                    <span className="w-6 h-6 rounded-full bg-forest text-sand text-xs font-mono font-bold flex items-center justify-center shrink-0 mt-0.5">
                      {idx + 1}
                    </span>
                    <blockquote className="text-base sm:text-lg font-serif font-bold text-forest leading-snug">
                      "{q.question}"
                    </blockquote>
                  </div>

                  <button
                    type="button"
                    onClick={() => handleCopyOne(q.id, `"${q.question}"`)}
                    className="p-2 rounded-xl bg-sand hover:bg-forest/5 border border-forest/15 text-forest/70 hover:text-forest transition-colors cursor-pointer shrink-0"
                    title="Copy question text"
                  >
                    {isCopied ? (
                      <Check className="w-3.5 h-3.5 text-emerald-600" />
                    ) : (
                      <Copy className="w-3.5 h-3.5" />
                    )}
                  </button>
                </div>

                {/* Purpose & Evidence to Look For Grid */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-3 pt-1">
                  <div className="p-3 rounded-2xl bg-sand border border-forest/10 space-y-1">
                    <span className="text-[10px] font-mono uppercase tracking-wider text-forest/60 font-bold">
                      Question Purpose:
                    </span>
                    <p className="text-xs text-forest/85 font-sans leading-relaxed">{q.purpose}</p>
                  </div>

                  <div className="p-3 rounded-2xl bg-sand border border-forest/10 space-y-1">
                    <span className="text-[10px] font-mono uppercase tracking-wider text-forest/60 font-bold">
                      Evidence to Look For:
                    </span>
                    <p className="text-xs text-forest/85 font-sans leading-relaxed">
                      {q.evidenceToLookFor}
                    </p>
                  </div>
                </div>

                {/* Follow-up Question */}
                {q.followUpQuestion && (
                  <div className="p-3 rounded-2xl bg-purple/10 border border-purple/20 flex items-start gap-2">
                    <CornerDownRight className="w-4 h-4 text-purple shrink-0 mt-0.5" />
                    <div className="space-y-0.5">
                      <span className="text-[10px] font-mono uppercase tracking-wider text-purple font-bold">
                        Recommended Follow-Up Probe:
                      </span>
                      <p className="text-xs font-serif italic text-forest/90">
                        "{q.followUpQuestion}"
                      </p>
                    </div>
                  </div>
                )}

                {/* Footer Reference */}
                {q.relatedAssumptionId && (
                  <div className="pt-2 border-t border-forest/10 flex items-center justify-between text-[11px] font-mono text-forest/60">
                    <span>Target Hypothesis: {q.relatedAssumptionId.slice(0, 8)}…</span>
                    {onSelectAssumption && (
                      <button
                        type="button"
                        onClick={() => onSelectAssumption(q.relatedAssumptionId)}
                        className="text-purple hover:underline font-bold flex items-center gap-1 cursor-pointer"
                      >
                        Inspect Assumption <ArrowRight className="w-3 h-3" />
                      </button>
                    )}
                  </div>
                )}
              </motion.div>
            );
          })}
        </div>
      )}
    </div>
  );
};
